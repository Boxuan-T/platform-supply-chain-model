function s = summarize_case(out)
R = out.R;
coop = R(:, 1)==8;
non = R(:, 1)==1;
s = struct('N', size(R, 1), 'basin', mean(coop), 'noncoop', mean(non), ...
'other', mean(R(:, 1)>0 & ~coop & ~non), 'unclassified', mean(R(:, 1)==0), ...
'nonhyperbolic', mean(R(:, 1)==-1), 'unstable', mean(R(:, 1)==-2), ...
'medianTc', median(R(coop, 2), 'omitnan'), 'meanW', mean(R(:, 8)), ...
'meanP', mean(R(:, 9)), 'meanM', mean(R(:, 10)), 'meanR', mean(R(:, 11)), ...
'maxHorizon', max(R(:, 13)));
end
